#!/usr/bin/env bash
# Builds the images and deploys the local stand to Docker Desktop Kubernetes,
# namespace expense-platform-local. Safe to re-run: data and secrets persist.
#
#   OBSERVABILITY=1  also deploy Prometheus with alert rules (localhost:30090)
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
CTX=docker-desktop
NS=expense-platform-local
source "$root/scripts/lib.sh"
guard_target "$CTX" "$NS"

step "Build images"
tags=()
for spec in expenses:services/expenses audit:services/audit devidp:tools/devidp; do
  name="${spec%%:*}"; dir="${spec#*:}"
  docker build -q -f "$root/$dir/Dockerfile" -t "expense-platform/$name:build" "$root" >/dev/null
  # Content-addressed tag: the node caches by tag, so a new build must get a new tag.
  id="$(docker image inspect -f '{{.Id}}' "expense-platform/$name:build" | cut -d: -f2 | cut -c1-12)"
  docker tag "expense-platform/$name:build" "expense-platform/$name:dev-$id"
  tags+=("$name=dev-$id")
  echo "expense-platform/$name:dev-$id"
done

step "Namespace and secrets"
kubectl --context "$CTX" apply -f "$root/deploy/k8s/overlays/local/namespace.yaml" >/dev/null
"$root/scripts/secrets.sh" "$CTX" "$NS"

step "Render manifests"
overlay=local
[[ "${OBSERVABILITY:-}" == 1 ]] && overlay=local-observability
gen="$root/.local/k8s/$overlay"
mkdir -p "$gen"
{
  echo "# Generated by scripts/deploy-local.sh; do not edit."
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "resources: [../../../deploy/k8s/overlays/$overlay]"
  echo "images:"
  for t in "${tags[@]}"; do echo "  - {name: expense-platform/${t%%=*}, newTag: ${t#*=}}"; done
} > "$gen/kustomization.yaml"

step "Apply"
# Jobs are immutable; delete finished setup jobs so they run again.
k delete job -l expense-platform/job=setup --ignore-not-found >/dev/null
kubectl --context "$CTX" apply -k "$gen" | grep -v unchanged || true

step "Wait for database setup"
k rollout status statefulset/postgres --timeout=180s
k wait --for=condition=complete job/db-bootstrap --timeout=180s
k wait --for=condition=complete job/expenses-migrate job/audit-migrate --timeout=180s

step "Wait for services"
for d in devidp audit expenses; do k rollout status "deployment/$d" --timeout=180s; done
[[ "$overlay" == local-observability ]] && k rollout status deployment/prometheus --timeout=180s

step "Port-forwards (127.0.0.1 only)"
"$root/scripts/port-forward.sh" start

"$root/scripts/status.sh"
